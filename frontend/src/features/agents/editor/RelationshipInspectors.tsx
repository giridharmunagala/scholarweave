function RelationshipAgents({
  blueprint,
  sourceLabel,
  source,
  targetLabel,
  target,
  onSourceChange,
  onTargetChange,
}: {
  blueprint: AgentBlueprint;
  sourceLabel: string;
  source: string;
  targetLabel: string;
  target: string;
  onSourceChange: (id: string) => void;
  onTargetChange: (id: string) => void;
}) {
  return (
    <div className="field-row">
      <label className="field">
        {sourceLabel}
        <select value={source} onChange={(event) => onSourceChange(event.target.value)}>
          {blueprint.agents
            .filter((agent) => agent.id !== target)
            .map((agent) => <option value={agent.id} key={agent.id}>{agent.name}</option>)}
        </select>
      </label>
      <label className="field">
        {targetLabel}
        <select value={target} onChange={(event) => onTargetChange(event.target.value)}>
          {blueprint.agents
            .filter((agent) => agent.id !== source)
            .map((agent) => <option value={agent.id} key={agent.id}>{agent.name}</option>)}
        </select>
      </label>
    </div>
  );
}
